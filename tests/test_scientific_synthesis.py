class ScientificOracleTests(unittest.TestCase):
    def test_correct_forward_reverse_and_different_power_controls(self):
        f=ORACLES['power_doubling_interval']
        for duration,power,given,expected in [(28,3,'powered',84),(84,3,'linear',28),(12,3,'powered',36),(10,2,'powered',20)]:
            target='linear' if given=='powered' else 'powered'
            self.assertEqual(f(duration,power,given=given,target=target,exponential=True,constant_shape=True),expected)
    def test_incompatible_and_unknown_assumptions_do_not_determine_interval(self):
        f=ORACLES['power_doubling_interval']
        for exponential,shape in [(False,True),(True,False),(None,True),(None,None)]:
            self.assertIsNone(f(28,3,given='powered',target='linear',exponential=exponential,constant_shape=shape))
        self.assertEqual(ORACLES['first_linear_volume_diameter_doubling'](28),196)
        self.assertNotEqual(196,84)  # linear initial interval differs from exponential doubling
    def test_inequality_membership_does_not_assert_observed_subgroup(self):
        self.assertTrue(28<=400);self.assertTrue(28<600)
        # Different populations can satisfy the same category with no overlap.
        self.assertTrue(all(x<=400 for x in [12,20]));self.assertTrue(all(x<=400 for x in [100,200]))
        self.assertFalse(set([12,20]) & set([100,200]))
    def test_noncomparable_endpoints_populations_causality_and_shared_evidence(self):
        left={'population':'subsolid nodules','endpoint':'growth category','metric':'AUC','design':'retrospective',
              'feature_effect_reported':False,'primary_evidence':['same-study']}
        right={'population':'adenocarcinoma nonsolid nodules','endpoint':'invasiveness','metric':'C-index','design':'retrospective',
               'feature_effect_reported':False,'primary_evidence':['same-study']}
        reasons=ORACLES['performance_comparison_limitations'](left,right)
        self.assertEqual(set(reasons),{'different_population','different_endpoint','different_metric',
            'aggregate_metrics_do_not_identify_feature_effect','shared_primary_evidence','causal_effect_not_established'})
