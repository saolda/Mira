class ScientificEvidenceTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.r=Research(self.tmp.name,ScriptedLLM([]),{})
        self.r.initialize('Compare scientific premises?', ['fixture'],context_budget=200000)
        seed(self.r,own=2,child=0,leaf=0)
        with self.r.store.lock():
            _,docs,eqs,_=self.r.store.read();state=loads(self.r.store._files()['research/state.json'])
        self.units=sy.records(state,docs,eqs)
    def test_question_cannot_supply_second_parent_in_s2_or_s3(self):
        units=deepcopy(self.units);units[1].update(type='question',structural_type='question')
        units[1]['fields']={'Question':'Does an unmeasured mechanism exist?'}
        accepted,rejected=sy.validate_s2(plans(idea()),units)
        self.assertEqual(accepted,[]);self.assertIn('substantive premises',rejected[0]['error'])
        with self.assertRaisesRegex(ValueError,'substantive premises'):sy.validate_s3(result(units),units,[])
    def test_question_context_does_not_disqualify_two_actual_premises(self):
        question=deepcopy(self.units[0]);question.update(id='r3#q1',memory_id='r3',type='question',structural_type='question')
        question['fields']={'Question':'What further measurements would test the hypothesis?'}
        units=self.units+[question]
        accepted,rejected=sy.validate_s2(plans(idea([u['id'] for u in units])),units)
        self.assertEqual(len(accepted),1);self.assertFalse(rejected)
        self.assertEqual(len(sy.validate_s3(result(units),units,[])),1)
    def test_equations_and_qualified_hypotheses_are_substantive_not_empirical_proof(self):
        for kinds in [('equation','equation'),('hypothesis','inference'),('claim','equation')]:
            units=deepcopy(self.units)
            for u,kind in zip(units,kinds):
                u['type']=kind;u['structural_type']='equation' if kind=='equation' else 'finding'
                u['fields']={'Expression':'V = k D^3','Qualification':'A defined mathematical premise, not an empirical observation.'} if kind=='equation' else {
                    'Proposition':'A proposed conditional mechanism.','Qualification':'An unverified hypothesis, not an established causal effect.'}
            accepted,rejected=sy.validate_s2(plans(idea()),units);self.assertEqual(len(accepted),1);self.assertFalse(rejected)
            value=result(units)
            for check,u in zip(value['findings'][0]['evidence_checks'],units):check['quote']=next(iter(u['fields'].values()))
            sy.validate_s3(value,units,[])
    def test_terminology_definition_cannot_supply_second_premise(self):
        units=deepcopy(self.units);units[1]['type']='definition'
        self.assertEqual(sy.validate_s2(plans(idea()),units)[0],[])
    def test_literal_colon_proposition_uses_lossless_expanded_fallback(self):
        proposition='The measurements have different roles: one is an input and one is an output.'
        value=result(self.units,self.units,proposition=proposition)
        self.r.llm=ScriptedLLM([plans(idea()),value])
        for action in ['S1','S2','S3']:
            event=self.r.step();self.assertEqual((event['action'],event['status']),(action,'committed'),event)
        memory=self.r.knowledge.document('s1')
        self.assertEqual(memory.units[0].fields['Proposition'],proposition)
        self.assertEqual(memory.metadata['storage_format'],'expanded_lossless_fallback')
        self.assertEqual(parse(render(memory)),memory)
        self.assertEqual({e.target for e in memory.relationships},{u['id'] for u in self.units})
        self.assertEqual(memory.metadata['scientific_validation']['status'],'unverified')
    def test_legacy_pending_question_objective_fails_durably_before_dispatch(self):
        with self.r.store.lock():
            token,docs,eqs,ledger=self.r.store.read();state=loads(self.r.store._files()['research/state.json'])
            docs[1].units.append(Unit(docs[1].allocate('q'),'Question',{'Question':'What is unmeasured?','State':'open'}))
            docs[1].revision+=1
            tree.refresh(state,docs);self.r.store.publish(docs,eqs,ledger,token,files={'research/state.json':dumps(state)})
        units=sy.records(state,docs,eqs);key=sd.fingerprint(units)
        group={'id':key,'unit_ids':[u['id'] for u in units],'unit_versions':[{'id':u['id'],'version':u['version']} for u in units],
            'memory_ids':['r1','r2'],'priority':1.,'relationships':[],'reason':'Historical group fixture.'}
        self.r.synthesis_discovery.discover=Mock(return_value=([group],{}));self.r.step()
        self.r.llm=ScriptedLLM([plans(idea(['r1#f1','r2#q1']))])
        # Reproduce the historical rule only while committing its old receipt.
        with patch.object(sy,'references',return_value=None):self.assertEqual(self.r.step()['status'],'committed')
        with tempfile.TemporaryDirectory() as legacy:
            copied=Path(legacy)/'completed';shutil.copytree(self.tmp.name,copied)
            old_units=[u for u in units if u['id'] in ['r1#f1','r2#q1']]
            old_model=ScriptedLLM([result(old_units,sy.novelty_context(old_units,units))])
            historical=Research(copied,old_model,{})
            with patch.object(sy,'references',return_value=None):self.assertEqual(historical.step()['status'],'committed')
            # New dispatch policy does not retrospectively invalidate completed
            # historical canonical memories or rewrite their unverified lineage.
            self.assertEqual(Research(copied,ScriptedLLM([]),{}).knowledge.validate()['documents'],3)
        restarted=Research(self.tmp.name,ScriptedLLM([]),{});event=restarted.step()
        self.assertEqual(event['status'],'rejected');self.assertIn('substantive premises',event['error']);self.assertFalse(restarted.llm.requests)
        self.assertEqual(next(iter(restarted.inspect()['unit_synthesis']['objectives'].values()))['status'],'failed')
        self.assertEqual(restarted.knowledge.validate()['documents'],2)
